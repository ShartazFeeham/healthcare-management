import { launch } from "./cdp.mjs";
const base = "http://localhost:3100";
const b = await launch({ port: 9344, width: 1440, height: 900 });
const p = await b.newPage();
const errors = [];
p.on((m) => {
  if (m.method === "Runtime.exceptionThrown") errors.push("EXC " + (m.params.exceptionDetails.exception?.description || "").slice(0, 200));
  if (m.method === "Network.loadingFailed") errors.push("NETFAIL " + m.params.errorText + " " + (m.params.canceled ? "(canceled)" : ""));
  if (m.method === "Network.responseReceived" && m.params.response.status >= 400) errors.push("HTTP " + m.params.response.status + " " + m.params.response.url);
});
await p.goto(base + "/public/login");
await p.screenshot("/tmp/shots/login.png");
console.log("title:", await p.eval("document.title"), "| body text:", (await p.eval("document.body.innerText")).slice(0, 120).replace(/\n/g, " | "));
await p.type("input[type=email]", "admin@healthcare.local");
await p.type("input[type=password]", "Admin@1234");
await p.click("text=Sign in");
await p.idle(1500);
console.log("url after login:", await p.eval("location.pathname"));
await p.screenshot("/tmp/shots/admin-home.png");
console.log(errors.slice(0, 15).join("\n"));
await b.close();
